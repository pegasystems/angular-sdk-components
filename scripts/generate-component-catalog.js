/*
 * Generates docs/components.md from the SDK component map so the catalogue cannot drift from the code.
 * Usage: node scripts/generate-component-catalog.js [--check]
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const mapFile = path.join(root, 'packages/angular-sdk-components/src/lib/_bridge/helpers/sdk-pega-component-map.ts');
const outFile = path.join(root, 'docs', 'components.md');

const source = fs.readFileSync(mapFile, 'utf8');
const imports = new Map();
for (const m of source.matchAll(/import \{\s*([A-Za-z0-9_]+)\s*\} from '\.\.\/\.\.\/_components\/([^']+)';/g)) {
  imports.set(m[1], m[2]);
}

const body = source.slice(source.indexOf('const pegaSdkComponentMap'));
const entries = [...body.matchAll(/^\s+([A-Za-z0-9_]+):\s*([A-Za-z0-9_]+),?\s*$/gm)].map(([, key, cls]) => ({ key, cls, file: imports.get(cls) }));

const byKind = {};
for (const e of entries) {
  const kind = e.file ? e.file.split('/')[0] : 'unknown';
  (byKind[kind] ||= []).push(e);
}

const lines = [
  '# Component catalogue',
  '',
  '<!-- Generated by `npm run docs:components`; do not edit by hand. -->',
  '',
  `${entries.length} Pega component names are mapped to Angular implementations. Override any of them through \`sdk-local-component-map.ts\` (see the overrides package).`,
  ''
];
for (const kind of Object.keys(byKind).sort()) {
  lines.push(`## ${kind}`, '', '| Pega component | Angular class | Source |', '| --- | --- | --- |');
  for (const e of byKind[kind].sort((a, b) => a.key.localeCompare(b.key))) {
    lines.push(`| \`${e.key}\` | \`${e.cls}\` | \`_components/${e.file}.ts\` |`);
  }
  lines.push('');
}
const output = `${lines.join('\n')}\n`.replace(/\n{3,}/g, '\n\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current !== output) {
    console.error('docs/components.md is out of date. Run: npm run docs:components');
    process.exit(1);
  }
  console.log('Component catalogue is up to date');
} else {
  fs.writeFileSync(outFile, output);
  console.log(`Wrote ${path.relative(root, outFile)} (${entries.length} components)`);
}
